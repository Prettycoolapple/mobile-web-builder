const CATALOGS: Record<Locale, Catalog> = { en, zh };

/**
 * Subdivision pathway callout header: use Chinese only when the device OS
 * primary locale is Chinese. English for all other OS locales.
 */
export function subdivisionPathwaySectionTitle(): string {
  const cat = isOSChineseLocale() ? zh : en;
  return cat["report.subdivision_pathway_title"] ?? en["report.subdivision_pathway_title"];
}

/**
 * UI strings for school zones and land title follow the device OS primary locale
 * only: Chinese when OS is Chinese, English otherwise.
 */
export function translateForOS(key: string, vars?: Record<string, string | number>): string {
  const cat = isOSChineseLocale() ? zh : en;
  const raw = cat[key] ?? en[key] ?? key;
  return interpolateFromCatalog(raw, vars);
}

function interpolateFromCatalog(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
}

interface LocaleContextValue {
  locale: Locale;
  setLocale: (l: Locale) => Promise<void>;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

function interpolate(template: string, vars?: Record<string, string | number>): string {
  return interpolateFromCatalog(template, vars);
}

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const detected = detectDeviceLocale();
    _setCurrentLocale(detected);
    return detected;
  });

  // App UI language follows the device primary locale only (zh* → Chinese, else English).
  useEffect(() => {
    const detected = detectDeviceLocale();
    setLocaleState(detected);
    _setCurrentLocale(detected);
  }, []);

  const setLocale = useCallback(async (_l: Locale) => {
    // Intentional no-op: locale is OS-driven only (no in-app override).
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const cat = CATALOGS[locale] ?? en;
      const raw = cat[key] ?? en[key] ?? key;
      return interpolate(raw, vars);
    },
    [locale],
  );

  return (
    <LocaleContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </LocaleContext.Provider>
  );
}

// Standalone translator that works without a LocaleProvider ancestor.
// Useful for error-boundary fallbacks rendered outside the provider tree
// and for one-off non-React call sites. Respects OS-detected Chinese locale.
export function translate(key: string, vars?: Record<string, string | number>): string {
  const locale = _currentLocale || detectDeviceLocale();
  const cat = CATALOGS[locale] ?? en;
  const raw = cat[key] ?? en[key] ?? key;
  return interpolate(raw, vars);
}

export function useT(): LocaleContextValue {
  const ctx = useContext(LocaleContext);
  if (!ctx) {
    const fallbackLocale = _currentLocale || detectDeviceLocale();
    return {
      locale: fallbackLocale,
      setLocale: async () => {},
      t: (key, vars) => {
        const cat = CATALOGS[fallbackLocale] ?? en;
        const raw = cat[key] ?? en[key] ?? key;
        return interpolate(raw, vars);
      },
    };
  }
  return ctx;
}

// Module-level access to current locale (for non-React code such as fetch helpers).
let _currentLocale: Locale = "en";
export function _setCurrentLocale(l: Locale) {
  _currentLocale = l;
}
export function getCurrentLocale(): Locale {
  return _currentLocale;
}

export function LocaleSync() {
  const { locale } = useT();
  useEffect(() => {
    _setCurrentLocale(locale);
  }, [locale]);
  return null;
}
