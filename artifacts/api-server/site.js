function isChinesePreferred() {
  const langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
  return langs.some((lang) => String(lang || "").toLowerCase().startsWith("zh"));
}

function applyChinese() {
  if (!isChinesePreferred()) return;

  document.documentElement.lang = "zh-Hans";
  const page = document.body.dataset.page || "home";
  const dict = { ...dictionaries.common, ...(dictionaries[page] || {}) };

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key && dict[key]) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key && dict[key]) el.setAttribute("placeholder", dict[key]);
  });

  if (dict.title) document.title = dict.title;
  const meta = document.querySelector('meta[name="description"]');
  if (meta && dict.meta) meta.setAttribute("content", dict.meta);

  window.__projectAlphaLang = "zh";
}

applyChinese();
